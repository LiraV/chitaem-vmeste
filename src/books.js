/** Ключ книги для запоминания показанных. */
export const bookKey = (b) => `${b.t}|${b.a}`;

/**
 * Случайные книги, которых читатель ещё не видел и которых нет у него на полке.
 * Когда пул исчерпан, память сбрасывается — лучше повтор через несколько сотен
 * книг, чем пустой экран.
 *
 * Внутри одной выдачи книги берутся из разных жанров: без этого случайный
 * выбор из пула, где детективов вчетверо больше, чем поэзии, регулярно
 * возвращал четыре детектива подряд и выглядел как поломка.
 *
 * @param {number} count Сколько нужно.
 * @param {string[]} seenKeys Уже показанные.
 * @param {string[]} shelfTitles Названия книг на полке читателя.
 * @param {string[]} genres Ограничить этими жанрами (пусто — все).
 */
export function pickBooks(count, seenKeys = [], shelfTitles = [], genres = []) {
  const seen = new Set(seenKeys);
  const onShelf = new Set(shelfTitles.map((s) => String(s).trim().toLowerCase()));
  const wanted = new Set(genres);
  const fits = (b) => !onShelf.has(b.t.toLowerCase()) && (!wanted.size || wanted.has(b.g));

  let pool = BOOK_POOL.filter((b) => fits(b) && !seen.has(bookKey(b)));
  let reset = false;
  if (pool.length < count) {
    pool = BOOK_POOL.filter(fits);
    reset = true;
  }
  if (!pool.length) {
    pool = BOOK_POOL.filter((b) => !seen.has(bookKey(b)));
    reset = true;
  }
  if (!pool.length) { pool = BOOK_POOL.slice(); reset = true; }

  // Раскладываем пул по жанрам и обходим корзины по кругу, беря из каждой
  // случайную книгу: так в выдаче из четырёх книг будет до четырёх жанров.
  const buckets = new Map();
  pool.forEach((b) => {
    const k = b.g || "other";
    if (!buckets.has(k)) buckets.set(k, []);
    buckets.get(k).push(b);
  });
  const order = [...buckets.keys()].sort(() => Math.random() - 0.5);

  const picked = [];
  while (picked.length < count && buckets.size) {
    for (const key of order) {
      const arr = buckets.get(key);
      if (!arr || !arr.length) { buckets.delete(key); continue; }
      picked.push(arr.splice(Math.floor(Math.random() * arr.length), 1)[0]);
      if (picked.length >= count) break;
    }
    if (order.every((k) => !buckets.get(k)?.length)) break;
  }
  return { picked, reset };
}
